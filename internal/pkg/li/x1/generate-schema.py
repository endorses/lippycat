#!/usr/bin/env python3
"""Regenerate X1 bindings and offline schemas; requires the pinned xgen binary."""

import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
XGEN_VERSION = "v0.0.0-20260902022537-fb39bae424fe"


def main():
    import argparse

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--xgen", default="xgen")
    args = parser.parse_args()
    args.xgen = shutil.which(args.xgen) or args.xgen
    metadata = subprocess.check_output(["go", "version", "-m", args.xgen], text=True)
    if "github.com/xuri/xgen\t" + XGEN_VERSION not in metadata:
        raise SystemExit("install github.com/xuri/xgen/cmd/xgen@" + XGEN_VERSION)
    manifest = json.loads((ROOT / "xsd/sources.json").read_text())
    paths = [ROOT / "xsd/upstream" / entry["file"] for entry in manifest]
    namespaces = {}
    for entry, path in zip(manifest, paths):
        if hashlib.sha256(path.read_bytes()).hexdigest() != entry["sha256"]:
            raise SystemExit("upstream source hash mismatch: " + path.name)
        if path.suffix == ".xsd":
            namespaces[ET.parse(path).getroot().attrib["targetNamespace"]] = path.name
    # Import locations are the only adjustments to the published schemas.
    for path in paths:
        content = path.read_text()
        if path.suffix == ".xsd":

            def locate(match):
                namespace = match.group(1)
                if namespace not in namespaces:
                    raise ValueError("unresolved offline import: " + namespace)
                return (
                    '<xs:import namespace="'
                    + namespace
                    + '" schemaLocation="'
                    + namespaces[namespace]
                    + '"/>'
                )

            content = re.sub(
                r'<xs:import namespace="([^"]+)"(?: schemaLocation="[^"]*")?\s*/>',
                locate,
                content,
            )
        (ROOT / "xsd" / path.name).write_text(content)
    with tempfile.TemporaryDirectory(prefix="lippycat-x1-codegen-") as temporary:
        output = Path(temporary) / "x1.go"
        subprocess.run(
            [
                args.xgen,
                "-i",
                str(ROOT / "xsd/upstream/TS_103_221_01.xsd"),
                "-o",
                str(output),
                "-p",
                "schema",
                "-l",
                "Go",
            ],
            check=True,
        )
        content = output.read_text()
        content = content.replace(
            "// Code generated by xgen. DO NOT EDIT.",
            "// Code generated by generate-schema.py using pinned xgen. DO NOT EDIT.",
        )
        # xgen has no polymorphic xsi:type model. Preserve the derived object in
        # an explicit runtime field whose strict XML codec is handwritten.
        content = content.replace(
            "type GenericObject struct {",
            'type GenericObject struct {\n IRIObject *iripolicy.Object `xml:"-"`',
        )
        # xgen emits extension bases last; XML Schema requires base fields first.
        content = re.sub(
            r"(type \w+ struct \{\n)([^}]*?)(\n\s*\*X1ResponseMessage)(\n\})",
            r"\1\t*X1ResponseMessage\n\2\4",
            content,
            flags=re.S,
        )
        content = content.replace(
            "IRIPolicyReference []*GenericObjectID", "IRIPolicyReference []*UUID"
        )
        content = content.replace(
            "package schema",
            'package schema\n\nimport "github.com/endorses/lippycat/internal/pkg/li/iripolicy"',
            1,
        )
        (ROOT / "schema/x1.go").write_text("//go:build li\n\n" + content)
    subprocess.run(["gofmt", "-w", str(ROOT / "schema/x1.go")], check=True)


if __name__ == "__main__":
    main()
