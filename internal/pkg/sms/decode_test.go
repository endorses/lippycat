func unhex(t testing.TB, s string) []byte {
	t.Helper()
	b, e := hex.DecodeString(s)
	if e != nil {
		t.Fatal(e)
	}
	return b
}
func rp(tp []byte, mt bool) []byte {
	kind := byte(0)
	if mt {
		kind = 1
	}
	b := []byte{kind, 0x23, 0, 0, byte(len(tp))}
	return append(b, tp...)
}
func submit(ud []byte, udl, dcs, first byte) []byte {
	b := []byte{first, 0, 5, 0x91, 0x21, 0x43, 0xf5, 0, dcs, udl}
	return append(b, ud...)
}

func TestDecodeKnownPackingAndDirection(t *testing.T) {
	// The GSM7 "hellohello" packing is the familiar worked SMS PDU example.
	// Expected text is fixed, not generated by the decoder or test packer.
	for _, tc := range []struct {
		name, tp, text, party string
		mt                    bool
		encoding              Encoding
	}{
		{"submit", "010005912143f500000ae8329bfd4697d9ec37", "hellohello", "+12345", false, EncodingGSM7},
		{"deliver", "0005912143f50000621042300405000ae8329bfd4697d9ec37", "hellohello", "+12345", true, EncodingGSM7},
		{"ucs2", "010005912143f5000806004103a94e2d", "AΩ中", "+12345", false, EncodingUCS2},
		{"empty", "010005912143f5000000", "", "+12345", false, EncodingGSM7},
		{"alpha", "010006d0c8321b000000", "", "Hel", false, EncodingGSM7},
	} {
		t.Run(tc.name, func(t *testing.T) {
			m, e := Decode(rp(unhex(t, tc.tp), tc.mt))
			if e != nil {
				t.Fatal(e)
			}
			if m.Status != StatusDecoded || m.Text != tc.text || m.Encoding != tc.encoding {
				t.Fatalf("unexpected message %#v", m)
			}
			if tc.mt {
				if m.From != tc.party || m.To != "" || m.Direction != DirectionMT {
					t.Fatalf("parties %#v", m)
				}
				want := time.Date(2026, 1, 24, 3, 40, 50, 0, time.UTC)
				if !m.Timestamp.Equal(want) {
					t.Fatalf("timestamp %v", m.Timestamp)
				}
			} else if m.To != tc.party || m.From != "" || m.Direction != DirectionMO {
				t.Fatalf("parties %#v", m)
			}
		})
	}
}

func TestValidityPeriods(t *testing.T) {
	for _, vpf := range []byte{0, 1, 2, 3} {
		tp := submit([]byte{0x41}, 1, 0, 1|vpf<<3)
		n := []int{0, 7, 1, 7}[vpf]
		vp := make([]byte, n)
		tp = append(append(append([]byte{}, tp[:9]...), vp...), tp[9:]...)
		m, e := Decode(rp(tp, false))
		if e != nil || m.Text != "A" {
			t.Fatalf("VPF %d: %#v %v", vpf, m, e)
		}
	}
}

// pack uses a simple bit-at-a-time writer independent of the decoder's shifts.
// It is used for structural offset coverage; literal fixtures cover packing too.
func pack(header []byte, septets []byte) ([]byte, byte) {
	n := (len(header)*8 + 6) / 7
	count := n + len(septets)
	out := make([]byte, (count*7+7)/8)
	copy(out, header)
	for i, v := range septets {
		for bit := 0; bit < 7; bit++ {
			if v&(1<<bit) != 0 {
				pos := n*7 + i*7 + bit
				out[pos/8] |= 1 << uint(pos%8)
			}
		}
	}
	return out, byte(count)
}

func TestUDHAndFillBits(t *testing.T) {
	for _, tc := range []struct {
		name      string
		header    []byte
		bits      uint8
		reference uint16
	}{
		{"ref8", []byte{5, 0, 3, 0x42, 2, 1}, 8, 0x42},
		{"ref16", []byte{6, 8, 4, 0x12, 0x34, 2, 1}, 16, 0x1234},
	} {
		t.Run(tc.name, func(t *testing.T) {
			ud, n := pack(tc.header, []byte{65, 27, 0x65, 66})
			m, e := Decode(rp(submit(ud, n, 0, 0x41), false))
			if e != nil {
				t.Fatal(e)
			}
			if m.Text != "A€B" || m.Concat == nil || m.Concat.ReferenceBits != tc.bits || m.Concat.Reference != tc.reference {
				t.Fatalf("unexpected %#v", m)
			}
		})
	}
	for padding := 0; padding < 7; padding++ {
		header := append([]byte{byte(padding + 2), 0x70, byte(padding)}, make([]byte, padding)...)
		ud, n := pack(header, []byte{65, 66, 67})
		m, e := Decode(rp(submit(ud, n, 0, 0x41), false))
		if e != nil || m.Text != "ABC" {
			t.Fatalf("fill %d: %#v %v", padding, m, e)
		}
	}
	udh := []byte{5, 0, 3, 4, 2, 2, 0x00, 0x41, 0x4e, 0x2d}
	m, e := Decode(rp(submit(udh, byte(len(udh)), 8, 0x41), false))
	if e != nil || m.Text != "A中" || m.Concat.Part != 2 {
		t.Fatalf("UCS2 header %#v %v", m, e)
	}
}

func TestAlphabetAndExtension(t *testing.T) {
	if len(gsmAlphabet) != 128 {
		t.Fatal(len(gsmAlphabet))
	}
	ud, n := pack(nil, []byte{0, 1, 2, 3, 4, 10, 13, 16, 32, 64, 91, 123, 127})
	m, e := Decode(rp(submit(ud, n, 0, 1), false))
	if e != nil || m.Text != "@£$¥è\n\rΔ ¡Ääà" {
		t.Fatalf("alphabet %q %v", m.Text, e)
	}
	ud, n = pack(nil, []byte{27, 10, 27, 20, 27, 40, 27, 41, 27, 47, 27, 60, 27, 61, 27, 62, 27, 64, 27, 101})
	m, e = Decode(rp(submit(ud, n, 0, 1), false))
	if e != nil || m.Text != "\f^{}\\[~]|€" {
		t.Fatalf("extensions %q %v", m.Text, e)
	}
}

func TestControlMessages(t *testing.T) {
	for _, b := range [][]byte{{2, 1}, {3, 1}, {4, 1, 1, 0x16}, {5, 1, 1, 0x16}, {6, 1}, {2, 1, 0x41, 1, 0}} {
		m, e := Decode(b)
		if e != nil || m.Status != StatusControl || m.Text != "" {
			t.Fatalf("control %#v %v", m, e)
		}
	}
	for _, tc := range []struct {
		tp []byte
		mt bool
	}{{[]byte{0}, false}, {[]byte{1}, true}, {[]byte{2}, true}} {
		m, e := Decode(rp(tc.tp, tc.mt))
		if e != nil || m.Status != StatusControl {
			t.Fatalf("TP report %#v %v", m, e)
		}
	}
}

func TestMalformedAndUnsupported(t *testing.T) {
	for _, tc := range []struct {
		name string
		body []byte
		want error
	}{
		{"missing", nil, ErrIncomplete},
		{"RP type", []byte{7, 0}, ErrUnsupported},
		{"RP trailing", []byte{6, 0, 1}, ErrMalformed},
		{"RP error cause", []byte{4, 0, 0}, ErrMalformed},
		{"RP length", []byte{0, 0, 0, 0, 255}, ErrIncomplete},
		{"odd UCS2", rp(submit([]byte{0}, 1, 8, 1), false), ErrMalformed},
		{"surrogate", rp(submit([]byte{0xd8, 0}, 2, 8, 1), false), ErrMalformed},
		{"escape", rp(submit([]byte{27}, 1, 0, 1), false), ErrMalformed},
		{"binary", rp(submit([]byte{65}, 1, 4, 1), false), ErrUnsupported},
		{"compressed", rp(submit([]byte{65}, 1, 0x20, 1), false), ErrUnsupported},
		{"reserved", rp(submit([]byte{65}, 1, 0x80, 1), false), ErrUnsupported},
		{"national", rp(submit([]byte{3, 0x25, 1, 0, 0}, 5, 0, 0x41), false), ErrUnsupported},
		{"UDH length", rp(submit([]byte{8}, 1, 8, 0x41), false), ErrMalformed},
		{"concat range", rp(submit([]byte{5, 0, 3, 2, 2, 3}, 6, 8, 0x41), false), ErrMalformed},
		{"UD size", rp(submit(make([]byte, 141), 141, 8, 1), false), ErrMalformed},
	} {
		t.Run(tc.name, func(t *testing.T) {
			m, e := Decode(tc.body)
			if !errors.Is(e, tc.want) || m.Status == StatusDecoded {
				t.Fatalf("got %#v %v want %v", m, e, tc.want)
			}
		})
	}
	body := rp(unhex(t, "010005912143f500000ae8329bfd4697d9ec37"), false)
	for n := 0; n < len(body); n++ {
		m, e := Decode(body[:n])
		if e == nil || m.Status == StatusDecoded {
			t.Fatalf("truncation %d: %#v %v", n, m, e)
		}
	}
}

func TestCodingGroups(t *testing.T) {
	for d := 0; d < 256; d++ {
		encoding, e := coding(byte(d))
		if e == nil && encoding != EncodingGSM7 && encoding != EncodingUCS2 {
			t.Fatalf("coding %x %s", d, encoding)
		}
	}
	for _, d := range []byte{0, 0x10, 0x40, 0x50, 0xc0, 0xd8, 0xf3} {
		if enc, e := coding(d); enc != EncodingGSM7 || e != nil {
			t.Fatalf("GSM7 %x %v", d, e)
		}
	}
	for _, d := range []byte{8, 0x18, 0x48, 0xe0} {
		if enc, e := coding(d); enc != EncodingUCS2 || e != nil {
			t.Fatalf("UCS2 %x %v", d, e)
		}
	}
}

