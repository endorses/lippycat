func FuzzDecode(f *testing.F) {
	f.Add([]byte{2, 0})
	f.Add(rp([]byte{1, 0, 0, 0x81, 0, 0, 0}, false))
	f.Add([]byte{})
	f.Fuzz(func(t *testing.T, b []byte) {
		m, e := Decode(b)
		if m == nil || !utf8.ValidString(m.Text) {
			t.Fatal("invalid result")
		}
		if e == nil && m.Status != StatusDecoded && m.Status != StatusControl {
			t.Fatal("unclassified success")
		}
		if e != nil && !errors.Is(e, ErrMalformed) && !errors.Is(e, ErrIncomplete) && !errors.Is(e, ErrUnsupported) {
			t.Fatal("unclassified error")
		}
		if len(m.Text) > 560 || len(m.Header) > 140 {
			t.Fatal("unbounded result")
		}
		if e != nil && strings.Contains(e.Error(), "\x00") {
			t.Fatal("payload in error")
		}
	})
}
